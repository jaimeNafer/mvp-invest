const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(fs.existsSync('app.js') ? 'app.js' : 'dist/app.js', 'utf8').split('\ndocument.addEventListener')[0];
const context = { document: { getElementById: () => ({}) }, localStorage: { getItem: () => null }, setTimeout, clearTimeout };
vm.runInNewContext(source + `
const assert = assertions;
let btc = state.positions[0];
assert.equal(equity(), 35540, 'watchlist must not count toward equity');
assert.equal(measure(btc).plannedLoss, 400);
assert.equal(measure(btc).pnl, 640);
assert.equal(measure(btc).giveback, 1040, 'giveback includes unrealized profit');
assert.ok(Math.abs(measure(btc).riskPct - 400/35540*100) < 1e-10);
state.scenario = 'stress';
assert.equal(contextStatus().level, 'red');
assert.equal(planStatus(btc).label, 'Dentro dos níveis');
assert.equal(measure(btc).pnl, 500, 'profit and red contextual alert must coexist');
const snap = snapshot(btc);
state.scenario = 'break';
assert.equal(planStatus(btc).label, 'Invalidação atingida');
assert.equal(measure(btc).pnl, -560, 'actual simulated loss can exceed planned loss');
assert.equal(snap.price, 78500, 'past decision context must remain unchanged');
state.scenario = 'target';
assert.equal(planStatus(btc).label, 'Objetivo alcançado');
state.scenario = 'mixed';
btc.qty = 10;
assert.equal(planStatus(btc).label, 'Risco acima do limite');
state = clone(BASE);
assert.equal(validState(state), true);
const data = new Map(Object.entries({...state.positions[0], stop: 77000}));
assert.throws(() => readPlan(data), /abaixo da entrada/);
const invalidTarget = new Map(Object.entries({...state.positions[0], target: 75000}));
assert.throws(() => readPlan(invalidTarget), /acima da entrada/);
const corrupt = clone(BASE); corrupt.positions[0].qty = -1;
assert.equal(validState(corrupt), false);
`, { ...context, assertions: assert });
console.log('PASS: risk, equity, scenario transitions, snapshot and plan validation');
